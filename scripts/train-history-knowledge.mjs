import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const truth = JSON.parse(fs.readFileSync(path.join(root, "data/history/ground-truth.json"), "utf8"));
const ocrSources = ["vision-ocr.json", "ppocrv6-ocr.json"]
  .map((name) => path.join(root, "data/history", name))
  .filter((file) => fs.existsSync(file))
  .map((file) => JSON.parse(fs.readFileSync(file, "utf8")));
const dailyTruthPath = path.join(root, "data/known-daily-ground-truth.json");
const dailyOcrPath = path.join(root, "data/known-daily-ppocrv6-ocr.json");

function normalizeKnowledgeText(value = "") {
  return String(value)
    .normalize("NFKC")
    .replace(/\r/g, "\n")
    .replace(/20\d{2}[-=./:]\d{1,2}[-=./:]\d{1,2}/g, " DATE ")
    .replace(/(?:^|[^\d])(?:[0-2]?\d)[:：.,·-][0-5]\d(?:\d)?(?!\d)/g, " TIME ")
    .replace(/(?:^|[^\d])(?:[0-2]\d)[0-5]\d(?!\d)/g, " TIME ")
    .replace(/星期[一二三四五六日天]/g, " WEEK ")
    .replace(/[晴阴雨雪雾多云]{1,3}\s*-?\d{1,2}\s*°?\s*[Cc]?/g, " WEATHER ")
    .replace(/防伪[^\n]*/g, "")
    .replace(/(?:今日水印|相机真实可验|相机\s*真实可验)/g, "")
    .replace(/工作单位[：:][^\n]*/g, "")
    .replace(/(?:备注|线路名称|线路)[：:][^\n]*(?:\n[SG]\d{1,4}[^\n]*)?/g, "")
    .replace(/海拔[：:]?\s*[\d.,，。]+\s*米?/g, "")
    .replace(/\b[A-Z0-9]{12,}\b/g, "")
    .replace(/\s+/g, "")
    .replace(/[，,。；;：:（）()【】[\]°]/g, "")
    .toLowerCase();
}

function eventFor(item) {
  if (item.eventType === "construction_supervision") return "construction";
  if (item.eventType === "overload_control") return "overload";
  return "";
}

function normalizedNameBase(item) {
  if (!item.expectedNormalizedName) return "";
  return item.expectedNormalizedName
    .replace(/\.[^.]+$/, "")
    .replace(/\d+$/, "");
}

const entries = truth.flatMap((item) => {
  const file = `data/history/${item.recordId}/${item.file}`;
  return ocrSources.flatMap((source) => {
    const ocr = source.find((entry) => entry.file === file);
    if (!ocr) return [];
    const normalizedText = normalizeKnowledgeText(ocr.text ?? "");
    if (!normalizedText) return [];
    return [{
    normalizedText,
    date: item.expectedTime?.slice(0, 10) ?? "",
    routeKey: item.route,
    place: item.benchmarkPoint,
    semanticPoint: item.semanticPoint,
    event: eventFor(item),
    expectedTime: item.expectedTime?.slice(11, 16) ?? "",
    include: item.include,
    recordHint: item.groupId,
    sessionHint: item.sessionId?.match(/-(\d+)$/)?.[1] ?? "",
    sequenceHint: item.sequenceIndex,
      nameBase: normalizedNameBase(item)
    }];
  });
});

if (fs.existsSync(dailyTruthPath) && fs.existsSync(dailyOcrPath)) {
  const dailyTruth = JSON.parse(fs.readFileSync(dailyTruthPath, "utf8"));
  const dailyOcr = new Map(
    JSON.parse(fs.readFileSync(dailyOcrPath, "utf8"))
      .map((item) => [item.file, item.text])
  );
  const groupOrder = new Map();
  for (const [folder, name, time, routeKey, place, include, recordHint] of dailyTruth) {
    const file = `daily/${folder}/${name}`;
    const normalizedText = normalizeKnowledgeText(dailyOcr.get(file) ?? "");
    if (!normalizedText) continue;
    const date = `20${folder.slice(0, 2)}-${folder.slice(2, 4)}-${folder.slice(4, 6)}`;
    const groupKey = recordHint || `${folder}:excluded`;
    const sequenceHint = (groupOrder.get(groupKey) || 0) + 1;
    groupOrder.set(groupKey, sequenceHint);
    const aliases = {
      "海东收费站入口": "海东主线收费站",
      "海东收费站出口": "海东主线收费站"
    };
    entries.push({
      normalizedText,
      date,
      routeKey,
      place,
      semanticPoint: place,
      event: "",
      expectedTime: time,
      include,
      recordHint,
      sessionHint: recordHint ? "1" : "",
      sequenceHint: include ? sequenceHint : null,
      nameBase: include ? (aliases[place] || place) : ""
    });
  }
}

const output = `// Generated by scripts/train-history-knowledge.mjs. Do not edit manually.\n`
  + `export default ${JSON.stringify(entries, null, 2)};\n`;
fs.writeFileSync(path.join(root, "src/history-knowledge.js"), output);

const duplicateGroups = Object.entries(Object.groupBy(entries, (item) => item.normalizedText))
  .filter(([text, items]) => text && items.length > 1)
  .map(([text, items]) => ({
    text: text.slice(0, 80),
    count: items.length,
    labels: [...new Set(items.map((item) => `${item.routeKey}/${item.place}`))]
  }));

console.log(`已生成 ${entries.length} 条历史知识特征。`);
if (duplicateGroups.length) console.log(JSON.stringify({ duplicateGroups }, null, 2));
